"""Build the scroll program book from the 19 canonical button pages."""

import argparse
import re
from hashlib import sha256
from pathlib import Path


DOCS = Path(__file__).resolve().parents[1] / "docs"
OUTPUT = DOCS / "scroll" / "index.html"
PAGES = ["index.html", *(f"{number:02}.html" for number in range(2, 20))]


def versioned_asset(name):
    source = (OUTPUT.parent / name).read_text(encoding="utf-8")
    digest = sha256(source.encode("utf-8")).hexdigest()[:12]
    return f"{name}?v={digest}"


def build():
    opening = (DOCS / PAGES[0]).read_text(encoding="utf-8")
    head = opening.split("</head>", 1)[0]
    head = re.sub(r"<title>[^<]*</title>", "<title>뮤지컬 〈난릉〉 웹 프로그램북</title>", head, count=1)
    head = head.replace('href="styles.css"', 'href="../styles.css"')
    head = head.replace('href="program-book.css"', 'href="../program-book.css"')
    sections = []

    for number, filename in enumerate(PAGES, 1):
        source = (DOCS / filename).read_text(encoding="utf-8")
        page = re.search(
            r'<main class="([^"]+)">(.*?)<nav class="pagination book-pagination"',
            source,
            re.DOTALL,
        )
        if not page:
            raise ValueError(f"Expected program-book markup in {filename}")

        classes, content = page.groups()
        page_id = f"page-{number:02}"
        heading = "h1" if number == 1 else "h2"
        content, heading_count = re.subn(
            r"<h1\b", f'<{heading} id="title-{number:02}"', content
        )
        if heading_count != 1:
            raise ValueError(f"Expected one heading in {filename}")
        content = content.replace("</h1>", f"</{heading}>")
        content = re.sub(
            r'href="(index\.html|\d{2}\.html)"',
            lambda match: f'href="#page-{PAGES.index(match[1]) + 1:02}"',
            content,
        )
        content = re.sub(r'(src|href)="assets/', r'\1="../assets/', content)
        footer = f'<span class="scroll-folio">{number:02} / {len(PAGES)}</span>'
        if number == 1:
            footer = '<a class="scroll-action" href="#page-02">아래로 스크롤 <span aria-hidden="true">↓</span></a>'
        elif number == len(PAGES):
            footer = '<a class="scroll-action" href="#page-02">목차로 돌아가기</a>' + footer
        elif number != 2:
            footer = '<a class="scroll-action" href="#page-02">목차</a>' + footer
        sections.append(
            f'    <section class="{classes}" id="{page_id}" aria-labelledby="title-{number:02}" tabindex="-1">'
            f'{content.rstrip()}\n      <footer class="scroll-footer">{footer}</footer>\n    </section>'
        )

    return (
        '<!-- Generated by scripts/build_scroll.py from the program-book pages. -->\n'
        f'{head}  <link rel="stylesheet" href="{versioned_asset("scroll.css")}">\n'
        f'  <script src="{versioned_asset("scroll.js")}" defer></script>\n'
        '</head>\n<body>\n  <main>\n' + "\n".join(sections) + '\n  </main>\n</body>\n</html>\n'
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check that the preview matches its source pages")
    preview = build()
    if parser.parse_args().check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != preview:
            parser.exit(1, "Run python scripts/build_scroll.py to regenerate the scroll preview.\n")
    else:
        OUTPUT.parent.mkdir(exist_ok=True)
        OUTPUT.write_text(preview, encoding="utf-8", newline="\n")
