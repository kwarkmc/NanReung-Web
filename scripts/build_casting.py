"""Render the two GitHub Pages casting board routes from one cast list."""

import argparse
from html import escape
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CASTING = ROOT / "docs" / "casting"


def render(data, scroll):
    cast = {actor["number"]: actor for actor in data["cast"]}
    assets = "../../assets/" if scroll else "../assets/"
    styles = "../casting.css" if scroll else "casting.css"
    script = "../../scroll/scroll.js" if scroll else "casting.js"
    mode = " casting-scroll" if scroll else ""
    cards = []
    profiles = []

    for number in data["grid"]:
        actor = cast[number]
        name, role = escape(actor["name"]), escape(actor["role"])
        index = f"{number:02}"
        badge = f'<span class="card-number" aria-hidden="true">{index}</span>' if number in data["numberedCards"] else ""
        tag = "a" if scroll else "button"
        destination = f'href="#cast-{index}"' if scroll else f'type="button" data-actor="{index}" aria-haspopup="dialog"'
        cards.append(
            f'      <{tag} class="cast-card" {destination}>\n'
            f'        <img src="{assets}cast-thumb-{index}.jpg" alt="" width="248" height="328">\n'
            f'        <span class="card-copy"><strong>{name}</strong><span>{role}</span></span>{badge}\n'
            f'      </{tag}>'
        )

    for number, actor in cast.items():
        index = f"{number:02}"
        name, role = escape(actor["name"]), escape(actor["role"])
        description = escape(actor["description"])
        name_id = f"cast-name-{index}"
        profile = (
            f'        <img class="cast-portrait chapter-header" src="{assets}cast-{index}.jpg" alt="{name}"'
            ' loading="lazy">\n'
            '        <div class="cast-copy chapter-content-2">\n'
            '          <div class="cast-identity">\n'
            f'            <h2 id="{name_id}">{name}</h2>\n'
            f'            <p>{role}</p>\n'
            '          </div>\n'
            f'          <p class="cast-description">{description}</p>\n'
            '        </div>'
        )
        if scroll:
            counter = f"{index} / {len(cast):02}"
            back = '<a href="#casting-list">목록으로 <span aria-hidden="true">↑</span></a>' if number == len(cast) else ""
            profiles.append(
                f'    <section class="cast-scene book-page" id="cast-{index}" aria-labelledby="{name_id}" tabindex="-1">\n'
                '      <article class="cast-panel">\n'
                '        <header class="profile-header">CAST PROFILE</header>\n'
                f'{profile}\n'
                f'        <footer class="cast-count">{counter}{back}</footer>\n'
                '      </article>\n'
                '    </section>'
            )
        else:
            profiles.append(f'      <article class="cast-detail" data-profile="{index}" hidden>\n{profile}\n      </article>')

    cards_markup = "\n".join(cards)
    profiles_markup = "\n".join(profiles)
    if scroll:
        detail = f'\n{profiles_markup}\n  </main>'
    else:
        detail = (
            '\n  </main>\n'
            '  <dialog class="casting-dialog cast-panel" aria-label="배우 프로필">\n'
            '    <header class="profile-header">CAST PROFILE'
            '<button type="button" data-close aria-label="프로필 닫기" autofocus>×</button></header>\n'
            f'{profiles_markup}\n'
            '    <nav class="cast-pagination" aria-label="프로필 이동">\n'
            '      <button type="button" data-step="-1">‹ 이전</button>\n'
            '      <output aria-live="polite"></output>\n'
            '      <button type="button" data-step="1">다음 ›</button>\n'
            '    </nav>\n'
            '  </dialog>'
        )

    return f"""<!doctype html>
<!-- Generated by scripts/build_casting.py from scripts/casting_data.json. -->
<html lang="ko">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="description" content="뮤지컬 〈난릉〉의 출연진과 배역 소개">
  <title>캐스팅보드 | 뮤지컬 〈난릉〉</title>
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500&amp;family=Noto+Sans+KR:wght@400;500&amp;family=Noto+Serif+KR:wght@400;500;600;700&amp;display=swap">
  <link rel="stylesheet" href="{styles}">
  <script src="{script}" defer></script>
</head>
<body class="casting{mode}">
  <main class="casting-shell">
    <section class="cast-board" id="casting-list" aria-labelledby="casting-title">
      <header class="board-header">
        <p>뮤지컬 &lt;난릉&gt;</p>
        <h1 id="casting-title">CASTING BOARD</h1>
        <span class="header-brush" aria-hidden="true"></span>
      </header>
      <h2>출연진</h2>
      <div class="cast-grid">
{cards_markup}
      </div>
    </section>{detail}
</body>
</html>
"""


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check that both pages match their source data")
    args = parser.parse_args()
    data = json.loads((ROOT / "scripts" / "casting_data.json").read_text(encoding="utf-8"))

    for scroll in (False, True):
        directory = CASTING / "scroll" if scroll else CASTING
        target = directory / "index.html"
        html = render(data, scroll)
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8") != html:
                parser.exit(1, f"Run python scripts/build_casting.py to regenerate {target.relative_to(ROOT)}.\n")
        else:
            directory.mkdir(parents=True, exist_ok=True)
            target.write_text(html, encoding="utf-8", newline="\n")
